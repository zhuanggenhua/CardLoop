using System;
using System.IO;
using System.Linq;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;

namespace GameCore
{
    [InitializeOnLoad]
    internal static class SceneMenuRegistry
    {
        private const string GeneratedFilePath = "Assets/Editor/GameCore/Generated/GameCoreSceneMenu.g.cs";
        private const string SceneMenuRoot = "场景";

        static SceneMenuRegistry()
        {
            EditorApplication.delayCall += EnsureGeneratedMenuFile;
        }

        [MenuItem(SceneMenuRoot + "/Refresh Scene Menu", priority = 0)]
        private static void RefreshSceneMenu()
        {
            EnsureGeneratedMenuFile();
            AssetDatabase.Refresh();
        }

        internal static void OpenScene(string scenePath)
        {
            if (!EditorSceneManager.SaveCurrentModifiedScenesIfUserWantsTo())
            {
                return;
            }

            EditorSceneManager.OpenScene(scenePath);
        }

        private static void EnsureGeneratedMenuFile()
        {
            // 人类可见场景菜单的单一真相源是 Assets 下全部场景资产。
            // Build Settings 只负责构建配置，不再决定编辑器场景菜单列表。
            string generatedCode = BuildGeneratedCode(SceneUtil.CreateSceneEntrySnapshot());

            string absolutePath = Path.GetFullPath(GeneratedFilePath);
            string directoryPath = Path.GetDirectoryName(absolutePath);
            if (!string.IsNullOrEmpty(directoryPath) && !Directory.Exists(directoryPath))
            {
                Directory.CreateDirectory(directoryPath);
            }

            if (File.Exists(absolutePath))
            {
                string existingCode = File.ReadAllText(absolutePath);
                if (string.Equals(existingCode, generatedCode, StringComparison.Ordinal))
                {
                    return;
                }
            }

            File.WriteAllText(absolutePath, generatedCode, new UTF8Encoding(false));
            AssetDatabase.ImportAsset(GeneratedFilePath, ImportAssetOptions.ForceSynchronousImport);
        }

        private static string BuildGeneratedCode(SceneUtil.SceneEntry[] entries)
        {
            StringBuilder builder = new();
            builder.AppendLine("// <auto-generated />");
            builder.AppendLine("// This file is generated by GameCore.SceneMenuRegistry.");
            builder.AppendLine("using UnityEditor;");
            builder.AppendLine();
            builder.AppendLine("namespace GameCore");
            builder.AppendLine("{");
            builder.AppendLine("    internal static class GameCoreSceneMenu");
            builder.AppendLine("    {");

            for (int i = 0; i < entries.Length; i++)
            {
                SceneUtil.SceneEntry entry = entries[i];
                string relativeMenuPath = GetMenuPath(entry.Path);
                string menuPath = EscapeForCSharp($"{SceneMenuRoot}/{relativeMenuPath}");
                string scenePath = EscapeForCSharp(entry.Path.Replace('\\', '/'));
                string methodName = $"OpenScene_{i:000}_{SanitizeIdentifier(relativeMenuPath)}";

                builder.AppendLine($"        [MenuItem(\"{menuPath}\", priority = {1000 + i})]");
                builder.AppendLine($"        private static void {methodName}()");
                builder.AppendLine("        {");
                builder.AppendLine($"            SceneMenuRegistry.OpenScene(\"{scenePath}\");");
                builder.AppendLine("        }");
                builder.AppendLine();
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");
            return builder.ToString();
        }

        private static string EscapeForCSharp(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }

        internal static string GetMenuPath(string scenePath)
        {
            string normalizedPath = scenePath.Replace('\\', '/');
            if (normalizedPath.StartsWith("Assets/", StringComparison.OrdinalIgnoreCase))
            {
                normalizedPath = normalizedPath.Substring("Assets/".Length);
            }

            const string sceneExtension = ".unity";
            if (normalizedPath.EndsWith(sceneExtension, StringComparison.OrdinalIgnoreCase))
            {
                normalizedPath = normalizedPath.Substring(0, normalizedPath.Length - sceneExtension.Length);
            }

            return normalizedPath;
        }

        private static string SanitizeIdentifier(string value)
        {
            StringBuilder builder = new();
            foreach (char character in value)
            {
                builder.Append(char.IsLetterOrDigit(character) ? character : '_');
            }

            if (builder.Length == 0 || char.IsDigit(builder[0]))
            {
                builder.Insert(0, '_');
            }

            return builder.ToString();
        }
    }
}
